const dicts: Record<Lang, Dict> = { en, th };

function loadLang(): Lang {
  try {
    const saved = localStorage.getItem("ourshell.lang");
    if (saved === "en" || saved === "th") return saved;
  } catch {
    /* localStorage unavailable - fall back to en */
  }
  return "en";
}

export const lang = writable<Lang>(loadLang());

lang.subscribe((l) => {
  try {
    document.documentElement.lang = l;
    document.documentElement.setAttribute("lang", l);
    localStorage.setItem("ourshell.lang", l);
  } catch {
    /* ignore */
  }
});

/** Formats `{name}` placeholders in a translated string, e.g. `format(t("a"), {n: 3})`. */
export function format(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key) => {
    const v = vars[key];
    return v === undefined ? match : String(v);
  });
}

/** Looks up `key` in dictionary `l`, falling back to English, then the key itself. */
export function translate(l: Lang, key: string): string {
  return dicts[l][key] ?? en[key] ?? key;
}

/** Reactive translator: `$t("hosts.title")` in markup, `get(t)("hosts.title")` in scripts. */
export const t = derived(lang, ($lang) => (key: string) => translate($lang, key));
